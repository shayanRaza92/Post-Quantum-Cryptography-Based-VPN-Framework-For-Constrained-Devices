#!/usr/bin/env python3
"""Check the firmware's ML-DSA-44/65/87 builds against dilithium-py and write the
known-answer values the ESP32 checks before it measures anything.

What it does:
  1. Builds host_check.c on the laptop together with the SAME ML-DSA unit files the
     firmware uses (arduino_libraries/MLDSA_Levels/src/).
  2. Runs it. For each level it prints the public key made from seed 0x00..0x1F and the
     deterministic signature of message 0x60..0x7F (empty context).
  3. Computes the same values with dilithium-py 1.5.1, a separate FIPS 204
     implementation, and requires them to be identical byte for byte.
  4. Writes firmware/sig_bench_unified/test_vectors.h with the SHA-256 of each expected
     public key and signature.

Needs gcc and dilithium-py 1.5.1:   pip install dilithium-py==1.5.1
Run:   python3 tools/mldsa_vectors/gen_mldsa_vectors.py
"""
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path

try:
    import importlib.metadata as md
    from dilithium_py.ml_dsa import ML_DSA_44, ML_DSA_65, ML_DSA_87
except ImportError:
    sys.exit("dilithium-py is missing. Install it with: pip install dilithium-py==1.5.1")

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]                                    # Drone_Auth_Research/
SKETCH = ROOT / "firmware" / "sig_bench_unified"
UNITS = ROOT / "arduino_libraries" / "MLDSA_Levels" / "src"
OUT_HEADER = SKETCH / "test_vectors.h"

SEED = bytes(range(32))
MSG = bytes(range(0x60, 0x80))
LEVELS = {44: ML_DSA_44, 65: ML_DSA_65, 87: ML_DSA_87}


def run_host_build():
    """Build and run host_check with the firmware's unit files. Returns {line tag: value}."""
    with tempfile.TemporaryDirectory() as tmp:
        exe = Path(tmp) / "host_check"
        cmd = ["gcc", "-O2", "-std=c99", "-D_DEFAULT_SOURCE",
               "-I", str(HERE / "shim"), "-I", str(UNITS),
               str(HERE / "host_check.c"), str(HERE / "shim" / "host_random.c"),
               *(str(UNITS / f"mldsa{lvl}_unit.c") for lvl in LEVELS),
               "-o", str(exe)]
        subprocess.run(cmd, check=True)
        out = subprocess.run([str(exe)], capture_output=True, text=True)
    if out.returncode != 0:
        sys.exit(f"host_check failed with code {out.returncode} (see host_check.c for its meaning)")
    values = {}
    for line in out.stdout.splitlines():
        tag, _, val = line.partition(" ")
        values[tag] = val
    return values


def main():
    host = run_host_build()
    rows = []
    for lvl, ref in LEVELS.items():
        pk, sk = ref.key_derive(SEED)
        sig = ref.sign(sk, MSG, ctx=b"", deterministic=True)
        assert ref.verify(pk, MSG, sig), "dilithium-py could not verify its own signature"
        if f"OK{lvl}" not in host:
            sys.exit(f"ML-DSA-{lvl}: the firmware build failed its own checks")
        if host[f"PK{lvl}"] != pk.hex():
            sys.exit(f"ML-DSA-{lvl}: public key differs from dilithium-py")
        if host[f"SIG{lvl}"] != sig.hex():
            sys.exit(f"ML-DSA-{lvl}: deterministic signature differs from dilithium-py")
        print(f"ML-DSA-{lvl}: public key ({len(pk)} B) and signature ({len(sig)} B) identical to dilithium-py")
        rows.append((lvl, hashlib.sha256(pk).digest(), hashlib.sha256(sig).digest(), len(sig)))

    def c_bytes(b):
        h = [f"0x{x:02x}" for x in b]
        return ",\n    ".join(", ".join(h[i:i + 8]) for i in range(0, len(h), 8))

    lines = [
        "// test_vectors.h - generated by tools/mldsa_vectors/gen_mldsa_vectors.py. Do not edit.",
        f"// Expected values from dilithium-py {md.version('dilithium-py')} (independent FIPS 204 code),",
        "// confirmed identical to this firmware's ML-DSA builds running on the laptop.",
        "// Inputs: seed = 0x00..0x1F, message = 0x60..0x7F, empty context, deterministic signing (rnd = 0).",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for lvl, pk_hash, sig_hash, siglen in rows:
        lines += [
            f"static const uint8_t KAT_MLDSA{lvl}_PK_SHA256[32] = {{\n    {c_bytes(pk_hash)} }};",
            f"static const uint8_t KAT_MLDSA{lvl}_SIG_SHA256[32] = {{\n    {c_bytes(sig_hash)} }};",
            f"static const uint32_t KAT_MLDSA{lvl}_SIG_LEN = {siglen};",
            "",
        ]
    OUT_HEADER.write_text("\n".join(lines))
    print(f"wrote {OUT_HEADER.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
