-- drone_auth.lua - Wireshark plug-in that names the Step 3 drone authentication messages
-- (UDP port 47000; formats in firmware/sig_bench_unified/link_protocol.h).
--
-- Use:  wireshark -X lua_script:tools/wireshark/drone_auth.lua results/e3/raw/link_<...>/capture.pcapng
-- or copy this file to ~/.local/lib/wireshark/plugins/ and restart Wireshark.
-- Real MAVLink 2 runs (styles tunnel/v2ext): this plug-in decodes the MAVLink 2 packet itself
-- (header, TUNNEL / V2_EXTENSION fields, checksum recomputed with MAVLink's CRC-16/MCRF4XX and the
-- message's CRC_EXTRA from c_library_v2) and names the authentication fragment it carries.
-- (tools/wireshark/mavlink_2_common.lua is the full dissector generated by pymavlink's mavgen; it is
--  not needed for this capture.)
-- Display filter examples:  droneauth.type == 5     droneauth.alg == 3     droneauth.frame_count > 1

local p = Proto("droneauth", "Drone Authentication (Step 3)")

local TYPES = { [1] = "HELLO", [2] = "GETKEY", [3] = "PUBKEY", [4] = "CHALLENGE", [5] = "AUTH",
                [6] = "RESULT", [7] = "STAT", [8] = "DONE" }
local ALGS = { [0] = "Ed25519", [1] = "ECDSA P-256", [2] = "RSA-3072", [3] = "ML-DSA-44",
               [4] = "ML-DSA-65", [5] = "ML-DSA-87" }
local STYLES = { [0] = "udp", [1] = "mav", [2] = "tunnel", [3] = "v2ext" }
local MAVLINK_MSG = { [385] = "TUNNEL", [248] = "V2_EXTENSION" }
local CRC_EXTRA = { [385] = 147, [248] = 8 }      -- MAVLINK_MSG_ID_*_CRC in c_library_v2
local bx = bit32 or bit

local function mavlink_crc(tvb, first, last, extra)   -- CRC-16/MCRF4XX as in checksum.h
  local crc = 0xFFFF
  local function acc(b)
    local tmp = bx.band(bx.bxor(b, bx.band(crc, 0xFF)), 0xFF)
    tmp = bx.band(bx.bxor(tmp, bx.lshift(tmp, 4)), 0xFF)
    crc = bx.band(bx.bxor(bx.rshift(crc, 8), bx.lshift(tmp, 8), bx.lshift(tmp, 3), bx.rshift(tmp, 4)), 0xFFFF)
  end
  for i = first, last do acc(tvb(i, 1):uint()) end
  acc(extra)
  return crc
end

local f = p.fields
f.type = ProtoField.uint8("droneauth.type", "Message type", base.DEC, TYPES)
f.alg = ProtoField.uint8("droneauth.alg", "Algorithm", base.DEC, ALGS)
f.style = ProtoField.uint8("droneauth.style", "Link style", base.DEC, STYLES)
f.seq = ProtoField.uint16("droneauth.seq", "Sequence")
f.dlen = ProtoField.uint16("droneauth.data_len", "Data length")
f.slen = ProtoField.uint16("droneauth.sig_len", "Signature / key length")
f.data = ProtoField.bytes("droneauth.data", "Data")
f.sig = ProtoField.bytes("droneauth.signature", "Signature / public key")
f.frame_idx = ProtoField.uint8("droneauth.frame_index", "Frame index")
f.frame_count = ProtoField.uint8("droneauth.frame_count", "Frame count")
f.frame_len = ProtoField.uint16("droneauth.frame_payload_len", "Frame payload length")
f.frame_payload = ProtoField.bytes("droneauth.frame_payload", "Frame payload (part of the message)")
f.mav_msg = ProtoField.string("droneauth.mavlink_msg", "Carried in MAVLink 2 message")
f.frag_len = ProtoField.uint8("droneauth.fragment_len", "Bytes of the signed message in this packet")
f.m_magic = ProtoField.uint8("droneauth.mavlink.magic", "Magic (MAVLink 2)", base.HEX)
f.m_len = ProtoField.uint8("droneauth.mavlink.len", "Payload length (after trailing-zero truncation)")
f.m_incompat = ProtoField.uint8("droneauth.mavlink.incompat_flags", "Incompatibility flags", base.HEX)
f.m_compat = ProtoField.uint8("droneauth.mavlink.compat_flags", "Compatibility flags", base.HEX)
f.m_seq = ProtoField.uint8("droneauth.mavlink.seq", "Packet sequence")
f.m_sys = ProtoField.uint8("droneauth.mavlink.sysid", "System ID")
f.m_comp = ProtoField.uint8("droneauth.mavlink.compid", "Component ID")
f.m_msgid = ProtoField.uint24("droneauth.mavlink.msgid", "Message ID", base.DEC, MAVLINK_MSG)
f.m_type16 = ProtoField.uint16("droneauth.mavlink.type", "payload_type / message_type (local experiment > 32767)")
f.m_tnet = ProtoField.uint8("droneauth.mavlink.target_network", "target_network")
f.m_tsys = ProtoField.uint8("droneauth.mavlink.target_system", "target_system")
f.m_tcomp = ProtoField.uint8("droneauth.mavlink.target_component", "target_component")
f.m_plen = ProtoField.uint8("droneauth.mavlink.payload_length", "payload_length")
f.m_payload = ProtoField.bytes("droneauth.mavlink.payload", "payload")
f.m_crc = ProtoField.uint16("droneauth.mavlink.checksum", "Checksum", base.HEX)
f.m_crc_ok = ProtoField.string("droneauth.mavlink.checksum_status", "Checksum status")

function p.dissector(buf, pinfo, tree)
  if buf:len() < 10 then return end
  if buf(0, 1):uint() == 0xFD and buf:len() >= 20 then
    -- real MAVLink 2 packet: 10-byte header, payload (len bytes), 2-byte checksum (little-endian).
    -- TUNNEL and V2_EXTENSION both have 5 bytes of fields before their payload array, where our
    -- 5-byte fragment header starts.
    local msgid = buf(7, 1):uint() + buf(8, 1):uint() * 256 + buf(9, 1):uint() * 65536
    local plen = buf(1, 1):uint()
    local m = tree:add(p, buf(0, math.min(buf:len(), 12 + plen)),
      "MAVLink 2 packet: " .. (MAVLINK_MSG[msgid] or ("message " .. msgid)))
    local h = m:add(buf(0, 10), "Header")
    h:add(f.m_magic, buf(0, 1)); h:add(f.m_len, buf(1, 1)); h:add(f.m_incompat, buf(2, 1))
    h:add(f.m_compat, buf(3, 1)); h:add(f.m_seq, buf(4, 1)); h:add(f.m_sys, buf(5, 1))
    h:add(f.m_comp, buf(6, 1)); h:add_le(f.m_msgid, buf(7, 3))
    if buf:len() >= 12 + plen then
      local pl = m:add(buf(10, plen), "Payload (" .. plen .. " bytes)")
      pl:add_le(f.m_type16, buf(10, 2))
      if msgid == 248 then
        pl:add(f.m_tnet, buf(12, 1)); pl:add(f.m_tsys, buf(13, 1)); pl:add(f.m_tcomp, buf(14, 1))
      else
        pl:add(f.m_tsys, buf(12, 1)); pl:add(f.m_tcomp, buf(13, 1)); pl:add(f.m_plen, buf(14, 1))
      end
      if plen > 5 then pl:add(f.m_payload, buf(15, plen - 5)) end
      local got = buf(10 + plen, 2):le_uint()
      m:add_le(f.m_crc, buf(10 + plen, 2))
      if CRC_EXTRA[msgid] then
        local want = mavlink_crc(buf, 1, 9 + plen, CRC_EXTRA[msgid])
        m:add(f.m_crc_ok, got == want and "correct (MAVLink CRC-16/MCRF4XX with CRC_EXTRA)"
          or string.format("WRONG (expected 0x%04x)", want))
      end
    end
    local t = tree:add(p, buf(15, 5), "Drone Authentication fragment")
    t:add(f.mav_msg, MAVLINK_MSG[msgid] or tostring(msgid))
    t:add(f.type, 5); t:add(f.seq, buf(15, 2))
    t:add(f.frame_idx, buf(17, 1)); t:add(f.frame_count, buf(18, 1)); t:add(f.frag_len, buf(19, 1))
    pinfo.cols.protocol = "MAVLink 2"
    pinfo.cols.info = string.format("%s  AUTH seq=%d  part %d/%d (%d B of the signed message)",
      MAVLINK_MSG[msgid] or tostring(msgid), buf(15, 2):uint(), buf(17, 1):uint() + 1, buf(18, 1):uint(),
      buf(19, 1):uint())
    return
  end
  local magic = buf(0, 2):string()
  pinfo.cols.protocol = "DRONE-AUTH"
  local t = tree:add(p, buf(), "Drone Authentication")
  if magic == "DA" and buf:len() >= 12 then
    local mtype, alg = buf(3, 1):uint(), buf(4, 1):uint()
    t:add(f.type, buf(3, 1)); t:add(f.alg, buf(4, 1)); t:add(f.style, buf(5, 1))
    t:add(f.seq, buf(6, 2)); t:add(f.dlen, buf(8, 2)); t:add(f.slen, buf(10, 2))
    local dlen, slen = buf(8, 2):uint(), buf(10, 2):uint()
    if dlen > 0 and buf:len() >= 12 + dlen then t:add(f.data, buf(12, dlen)) end
    if slen > 0 and buf:len() >= 12 + dlen + slen then t:add(f.sig, buf(12 + dlen, slen)) end
    pinfo.cols.info = string.format("%s %s seq=%d data=%d sig=%d", TYPES[mtype] or "?",
      ALGS[alg] or "", buf(6, 2):uint(), dlen, slen)
  elseif magic == "DF" then
    local mtype, alg = buf(2, 1):uint(), buf(3, 1):uint()
    t:add(f.type, buf(2, 1)); t:add(f.alg, buf(3, 1)); t:add(f.seq, buf(4, 2))
    t:add(f.frame_idx, buf(6, 1)); t:add(f.frame_count, buf(7, 1)); t:add(f.frame_len, buf(8, 2))
    if buf:len() > 10 then t:add(f.frame_payload, buf(10)) end
    pinfo.cols.info = string.format("%s %s seq=%d frame %d/%d (%d B)", TYPES[mtype] or "?", ALGS[alg] or "",
      buf(4, 2):uint(), buf(6, 1):uint() + 1, buf(7, 1):uint(), buf(8, 2):uint())
  end
end

DissectorTable.get("udp.port"):add(47000, p)
