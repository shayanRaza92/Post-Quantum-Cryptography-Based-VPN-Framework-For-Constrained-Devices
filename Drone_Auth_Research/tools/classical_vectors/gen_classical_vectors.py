#!/usr/bin/env python3
"""Write the known-answer values for the classical algorithms (classical_vectors.h).

Each value is checked here with the Python `cryptography` package (OpenSSL), which is
independent of the ESP32's mbedTLS and libsodium:

  Ed25519      RFC 8032 section 7.1, test 1 (key from seed, signature of the empty message)
  ECDSA P-256  RFC 6979 appendix A.2.5, SHA-256, message "sample": known key and the
               deterministic signature (r, s). mbedTLS on the ESP32 signs deterministically
               (CONFIG_MBEDTLS_ECDSA_DETERMINISTIC=y), so it must produce exactly this (r, s).
  RSA-3072     PKCS#1 v1.5 with SHA-256 is deterministic: a fixed test key (made once, stored
               in the header) must give exactly the signature OpenSSL gives. Only its SHA-256
               is stored. The key is a TEST key, used for nothing else.

Run:  python3 tools/classical_vectors/gen_classical_vectors.py
Re-running keeps the existing RSA test key unless --new-rsa-key is given.
"""
import argparse
import hashlib
import re
import sys
from pathlib import Path

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec, ed25519, padding, rsa
from cryptography.hazmat.primitives.asymmetric.utils import encode_dss_signature

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "firmware" / "sig_bench_unified" / "classical_vectors.h"

# RFC 8032, section 7.1, TEST 1
ED_SEED = bytes.fromhex("9d61b19deffd5a60ba844af492ec2cc44449c5697b326919703bac031cae7f60")
ED_PK = bytes.fromhex("d75a980182b10ab7d54bfed3c964073a0ee172f3daa62325af021a68f707511a")
ED_SIG = bytes.fromhex("e5564300c360ac729086e2cc806e828a84877f1eb8e5d974d873e06522490155"
                       "5fb8821590a33bacc61e39701cf9b46bd25bf5f0595bbe24655141438e7a100b")

# RFC 6979, appendix A.2.5 (NIST P-256), SHA-256, message "sample"
EC_X = int("C9AFA9D845BA75166B5C215767B1D6934E50C3DB36E89B127B8A622B120F6721", 16)
EC_UX = int("60FED4BA255A9D31C961EB74C6356D68C049B8923B61FA6CE669622E60F29FB6", 16)
EC_UY = int("7903FE1008B8BC99A41AE9E95628BC64F2F1B20C2D7E9F5177A3C294D4462299", 16)
EC_R = int("EFD48B2AACB6A8FD1140DD9CD45E81D69D2C877B56AAF991C34D0EA84EAF3716", 16)
EC_S = int("F7CB1C942D657C41D436C7A1B6E29F65F3E900DBB9AFF4064DC4AB2F843ACDA8", 16)
EC_MSG = b"sample"

RSA_MSG = b"drone-auth known-answer test message"


def check_ed25519():
    key = ed25519.Ed25519PrivateKey.from_private_bytes(ED_SEED)
    pk = key.public_key().public_bytes(serialization.Encoding.Raw, serialization.PublicFormat.Raw)
    assert pk == ED_PK, "Ed25519 public key does not match RFC 8032"
    assert key.sign(b"") == ED_SIG, "Ed25519 signature does not match RFC 8032"


def check_ecdsa():
    key = ec.derive_private_key(EC_X, ec.SECP256R1())
    nums = key.public_key().public_numbers()
    assert (nums.x, nums.y) == (EC_UX, EC_UY), "P-256 public key does not match RFC 6979"
    der = encode_dss_signature(EC_R, EC_S)
    key.public_key().verify(der, EC_MSG, ec.ECDSA(hashes.SHA256()))  # raises if invalid
    return der


def rsa_key(new_key):
    if OUT.exists() and not new_key:
        m = re.search(r'R"PEM\((.*?)\)PEM"', OUT.read_text(), re.S)
        if m:
            return serialization.load_pem_private_key(m.group(1).encode(), password=None)
    return rsa.generate_private_key(public_exponent=65537, key_size=3072)


def c_bytes(b):
    h = [f"0x{x:02x}" for x in b]
    return ",\n    ".join(", ".join(h[i:i + 8]) for i in range(0, len(h), 8))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--new-rsa-key", action="store_true", help="make a new RSA-3072 test key")
    args = ap.parse_args()

    check_ed25519()
    print("Ed25519: RFC 8032 test 1 confirmed with OpenSSL")
    ec_der = check_ecdsa()
    print("ECDSA P-256: RFC 6979 A.2.5 key and signature confirmed with OpenSSL")

    key = rsa_key(args.new_rsa_key)
    assert key.key_size == 3072
    sig = key.sign(RSA_MSG, padding.PKCS1v15(), hashes.SHA256())
    assert sig == key.sign(RSA_MSG, padding.PKCS1v15(), hashes.SHA256()), "PKCS#1 v1.5 not deterministic?"
    try:
        key.public_key().verify(sig, RSA_MSG, padding.PKCS1v15(), hashes.SHA256())
    except InvalidSignature:
        sys.exit("RSA self-check failed")
    print("RSA-3072: PKCS#1 v1.5 / SHA-256 reference signature made with OpenSSL")
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.TraditionalOpenSSL,
                            serialization.NoEncryption()).decode()

    text = f"""// classical_vectors.h - generated by tools/classical_vectors/gen_classical_vectors.py. Do not edit.
// Known answers checked with the Python 'cryptography' package (OpenSSL), independent of mbedTLS/libsodium.
#pragma once
#include <stdint.h>

// Ed25519: RFC 8032 section 7.1, test 1 (empty message)
static const uint8_t KAT_ED25519_SEED[32] = {{
    {c_bytes(ED_SEED)} }};
static const uint8_t KAT_ED25519_PK[32] = {{
    {c_bytes(ED_PK)} }};
static const uint8_t KAT_ED25519_SIG[64] = {{
    {c_bytes(ED_SIG)} }};

// ECDSA P-256: RFC 6979 appendix A.2.5, SHA-256, message "sample"
static const char KAT_ECDSA_MSG[] = "sample";
static const char KAT_ECDSA_X_HEX[]  = "{EC_X:064X}";
static const char KAT_ECDSA_UX_HEX[] = "{EC_UX:064X}";
static const char KAT_ECDSA_UY_HEX[] = "{EC_UY:064X}";
static const uint8_t KAT_ECDSA_SIG_DER[{len(ec_der)}] = {{
    {c_bytes(ec_der)} }};

// RSA-3072 PKCS#1 v1.5 / SHA-256. TEST KEY ONLY: it exists to check mbedTLS against OpenSSL.
static const char KAT_RSA_MSG[] = "{RSA_MSG.decode()}";
static const char KAT_RSA_KEY_PEM[] = R"PEM({pem})PEM";
static const uint8_t KAT_RSA_SIG_SHA256[32] = {{
    {c_bytes(hashlib.sha256(sig).digest())} }};
"""
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
