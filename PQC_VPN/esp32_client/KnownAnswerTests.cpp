// ML-KEM-512 (FIPS 203): key generation, decapsulation, implicit rejection
static void katMlKem() {
  static uint8_t seed[64], ek[MLKEM512::PUBLIC_KEY_SIZE], dk[MLKEM512::SECRET_KEY_SIZE], ct[MLKEM512::CIPHERTEXT_SIZE];
  uint8_t digest[32], ss[32];
  fillCounting(seed, 64, 0x00);                         // d || z
  bool kg = MLKEM512::generateKeypairFromSeed(ek, dk, seed) == 0;
  crypto_hash_sha256(digest, ek, sizeof(ek));
  bool ekOk = kg && equalsHex(digest, REF_KEM_EK_SHA256);
  crypto_hash_sha256(digest, dk, sizeof(dk));
  bool dkOk = kg && equalsHex(digest, REF_KEM_DK_SHA256);
  result("ml_kem_512_keygen", "kyber-py (FIPS 203) d,z fixed", ekOk && dkOk);

  memcpy(ct, REF_KEM_CT, sizeof(ct));
  bool dec = MLKEM512::decapsulate(ss, ct, dk) == 0 && equalsHex(ss, REF_KEM_SS);
  result("ml_kem_512_decaps", "kyber-py ciphertext, m fixed", dec);

  ct[0] ^= 0x01;   // Tampered ciphertext: FIPS 203 returns the "implicit rejection" key K-bar
  bool rej = MLKEM512::decapsulate(ss, ct, dk) == 0 && equalsHex(ss, REF_KEM_SS_REJECT) && !equalsHex(ss, REF_KEM_SS);
  result("ml_kem_512_implicit_rejection", "kyber-py, 1 flipped ct bit", rej);

  // Round trip with the randomized API the VPN uses
  uint8_t ss2[32];
  bool rt = MLKEM512::encapsulate(ct, ss, ek) == 0 && MLKEM512::decapsulate(ss2, ct, dk) == 0 && memcmp(ss, ss2, 32) == 0;
  result("ml_kem_512_encaps_roundtrip", "random encaps -> decaps", rt);
  sodium_memzero(dk, sizeof(dk));
}

// ML-DSA-44 (FIPS 204): key generation, verify a reference signature, tamper, sign round trip
static void katMlDsa() {
  static uint8_t seed[32], pk[MLDSA44::PUBLIC_KEY_SIZE], sk[MLDSA44::SECRET_KEY_SIZE], sig[MLDSA44::SIGNATURE_SIZE];
  uint8_t msg[32], digest[32];
  fillCounting(seed, 32, 0x00);
  fillCounting(msg, 32, 0x60);
  bool kg = MLDSA44::generateKeypairFromSeed(pk, sk, seed) == 0;
  crypto_hash_sha256(digest, pk, sizeof(pk));
  bool pkOk = kg && equalsHex(digest, REF_DSA_PK_SHA256);
  crypto_hash_sha256(digest, sk, sizeof(sk));
  bool skOk = kg && equalsHex(digest, REF_DSA_SK_SHA256);
  result("ml_dsa_44_keygen", "dilithium-py (FIPS 204) xi fixed", pkOk && skOk);

  memcpy(sig, REF_DSA_SIG, sizeof(sig));
  bool ver = MLDSA44::verify(sig, sizeof(sig), msg, sizeof(msg), pk) == 0;
  result("ml_dsa_44_verify_reference_sig", "dilithium-py deterministic sig", ver);

  sig[100] ^= 0x01;
  bool tamper = MLDSA44::verify(sig, sizeof(sig), msg, sizeof(msg), pk) != 0;
  result("ml_dsa_44_tamper_rejected", "1 flipped signature bit", tamper);

  size_t sigLen = 0;   // The VPN signs with randomized (hedged) signing: check it verifies
  bool rt = MLDSA44::sign(sig, &sigLen, msg, sizeof(msg), sk) == 0 && sigLen == sizeof(sig) &&
            MLDSA44::verify(sig, sigLen, msg, sizeof(msg), pk) == 0;
  result("ml_dsa_44_sign_roundtrip", "hedged sign -> verify", rt);
  sodium_memzero(sk, sizeof(sk));
}

bool runKnownAnswerTests() {
  gPassed = gTotal = 0;
  katSha256();
  katHmac();
  katAesGcm();
  katMlKem();
  katMlDsa();
  Serial.printf("  => %d / %d known-answer tests passed\n", gPassed, gTotal);
  return gPassed == gTotal;
}
